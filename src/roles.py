def get_role_abbreviation(role_name: str) -> str:
    """
    Возвращает сокращение роли по её названию.

    Args:
        role_name: Название роли

    Returns:
        Сокращение роли или неизвестная роль
    """
    return ROLES.get(role_name, 'Unknown')
