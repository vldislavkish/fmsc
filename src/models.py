def get_har_coefficient(character: str, press_relations: str) -> float:
    """
    Умный поиск коэффициента ХАР.
    1. Точное совпадение.
    2. Частичное совпадение (если в FM несколько черт через запятую).
    3. Среднее значение по данному Характеру.
    4. Дефолт 1.0.
    """
    if not character:
        return 1.0

    char = str(character).strip()
    press = str(press_relations).strip() if press_relations else ""

    # 1. Точное совпадение
    if (char, press) in HAR_LOOKUP:
        return HAR_LOOKUP[(char, press)]

    # 2. Частичное совпадение (например, игрок: "Открытый для прессы", а в базе: "Невозмутимый, Открытый для прессы")
    for (db_char, db_press), coeff in HAR_LOOKUP.items():
        if db_char == char and (press in db_press or db_press in press):
            return coeff

    # 3. Фоллбэк: среднее значение по данному Характеру
    char_coeffs = [v for (c, p), v in HAR_LOOKUP.items() if c == char]
    if char_coeffs:
        return round(sum(char_coeffs) / len(char_coeffs), 2)

    # 4. Если характер вообще не найден
    return 1.0
